// Performance & Architecture Audit V2 — detailed timer/context scan.
import fs from 'node:fs';
const html=fs.readFileSync('index.html','utf8');
const jsFiles=fs.readdirSync('.').filter(f=>f.endsWith('.js')).sort();
const runtime=[html,...jsFiles.map(f=>fs.readFileSync(f,'utf8'))].join('\n');
const count=(re,s=runtime)=>(s.match(re)||[]).length;
const named=(re,s=html)=>[...s.matchAll(re)].map(m=>m[1]).filter(Boolean);
const lineNo=i=>html.slice(0,i).split('\n').length;
const context=(i,r=220)=>html.slice(Math.max(0,i-r),Math.min(html.length,i+r)).replace(/\s+/g,' ').trim();
const listeners=count(/addEventListener\s*\(/g);
const observers=count(/new\s+MutationObserver\s*\(/g);
const timeouts=count(/setTimeout\s*\(/g);
const intervalMatches=[...html.matchAll(/setInterval\s*\(/g)];
const supabaseFrom=count(/\.from\s*\(\s*['"][^'"]+['"]\s*\)/g);
const supabaseRpc=count(/\.rpc\s*\(\s*['"][^'"]+['"]/g);
const innerHtml=count(/\.innerHTML\s*=/g);
const renderFns=named(/function\s+(render[A-Za-z0-9_$]+)\s*\(/g);
const globals=[...html.matchAll(/\b(?:const|let|var)\s+(v\d+[A-Za-z0-9_$]*Timer)\b/g)].map(m=>m[1]);
const report=[];
report.push('# Performance & Architecture Audit V2');
report.push('');
report.push(`- index.html: ${Buffer.byteLength(html)} bytes`);
report.push(`- root JS files: ${jsFiles.length}`);
report.push(`- addEventListener calls: ${listeners}`);
report.push(`- MutationObserver instances: ${observers}`);
report.push(`- setInterval calls in Legacy index: ${intervalMatches.length}`);
report.push(`- setTimeout calls: ${timeouts}`);
report.push(`- Supabase .from() call sites: ${supabaseFrom}`);
report.push(`- Supabase .rpc() call sites: ${supabaseRpc}`);
report.push(`- innerHTML assignments: ${innerHtml}`);
report.push(`- resident render* functions in index: ${renderFns.length}`);
report.push('');
report.push('## Legacy interval contexts');
for(const m of intervalMatches)report.push(`- line ${lineNo(m.index)}: ${context(m.index,260)}`);
report.push('');
report.push('## MutationObserver contexts');
for(const m of html.matchAll(/new\s+MutationObserver\s*\(/g))report.push(`- line ${lineNo(m.index)}: ${context(m.index,260)}`);
report.push('');
report.push('## Legacy timer globals');
for(const x of [...new Set(globals)])report.push(`- ${x}`);
report.push('');
report.push('## Resident render functions');
for(const x of renderFns)report.push(`- ${x}`);
report.push('');
report.push('## Root JS sizes');
for(const f of jsFiles)report.push(`- ${f}: ${fs.statSync(f).size} bytes`);
fs.mkdirSync('audit',{recursive:true});
fs.writeFileSync('audit/performance-architecture-v2.md',report.join('\n')+'\n');
console.log(report.join('\n'));
